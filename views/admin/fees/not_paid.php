$totalPendingMoney = 0;

if (!empty($studentsData)) {
    foreach ($studentsData as $s) {
        $start = new DateTime(date('Y-m-01', strtotime($s['enrolled_at'])));
        $cursor = clone $start;

        while ($cursor <= $today) {
            $month = (int)$cursor->format('m');
            $year = (int)$cursor->format('Y');

            // Skip unpayable (holiday) months
            if (isset($payableMonths[$year][$month]) && $payableMonths[$year][$month] === 0) {
                $cursor->modify('+1 month');
                continue;
            }

            // Apply month filter (if set)
            if ($filterMonth && $month !== $filterMonth) {
                $cursor->modify('+1 month');
                continue;
            }

            // Apply year filter (if set)
            if ($filterYear && $year !== $filterYear) {
                $cursor->modify('+1 month');
                continue;
            }

            // Fetch class fee from table OR use default
            $fee = $conn->query("
                SELECT id, amount FROM class_fees
                WHERE class_id = {$s['class_id']}
                AND month = $month AND year = $year
                LIMIT 1
            ")->fetch_assoc();

            // Determine fee amount
            $feeAmount = $fee['amount'] ?? ($defaultClassFees[$s['class_id']] ?? $defaultClassFees['default']);

            // Fetch discount
            $discount = $conn->query("
                SELECT discount_percentage 
                FROM student_discounts 
                WHERE student_id = {$s['student_id']} 
                AND created_at <= '{$cursor->format('Y-m-t')}' 
                ORDER BY created_at DESC 
                LIMIT 1
            ")->fetch_assoc();

            $discountPercentage = $discount['discount_percentage'] ?? 0;
            $finalAmount = $feeAmount - ($feeAmount * $discountPercentage / 100);

            // Calculate paid amount
            if ($fee && isset($fee['id'])) {
                $pay = $conn->query("
                    SELECT paid_amount
                    FROM student_fees
                    WHERE student_id = {$s['student_id']}
                    AND class_fee_id = {$fee['id']}
                    LIMIT 1
                ");
                $paidAmount = ($pay && $pay->num_rows > 0) ? $pay->fetch_assoc()['paid_amount'] : 0;
            } else {
                $paidAmount = array_sum($studentFees[$s['student_id']] ?? [0]);
            }

            // Skip fully paid students
            if ($paidAmount >= $finalAmount) {
                $cursor->modify('+1 month');
                continue;
            }

            // Calculate pending for this month
            $pending = max(0, $finalAmount - $paidAmount);
            $totalPendingMoney += $pending;

            $cursor->modify('+1 month');
        }
    }
