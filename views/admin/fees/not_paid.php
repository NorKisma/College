        8 => t('august'),
        9 => t('september'),
        10 => t('october'),
        11 => t('november'),
        12 => t('december')
    ];
    
    return $monthNames[$monthNumber] ?? date('F', mktime(0, 0, 0, $monthNumber, 1));
}

